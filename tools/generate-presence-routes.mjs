// Generate the per-app presence relay routes.
//
// WHY A GENERATOR
//
// Eight apps need the same three routes. Written by hand that is eight near-
// identical files, and eight is enough for one of them to drift - which is exactly
// what happened with five copies of `/api/health-check` (two of which leaked the
// internal topology) and seven of `/api/audit` (which drifted into three variants).
//
// A generator makes the eight identical BY CONSTRUCTION, and re-running it after a
// change fixes all eight or fails loudly. That property is worth more than the eight
// saved files, because the failure mode being defended against is not "someone
// forgets to copy a file" - it is "someone fixes one copy".
//
// WHAT IT WRITES
//
//   apps/<app>/src/app/api/auth/presence/start/route.ts
//   apps/<app>/src/app/api/auth/presence/heartbeat/route.ts
//   apps/<app>/src/app/api/auth/presence/end/route.ts
//
// Each is a three-line re-export of `@wideo11/ui/presence-handler`. Identical in
// all eight apps, which is the point.
//
// APPS THAT USE `app/` INSTEAD OF `src/app/`
//
// `apps/analytics` has its router at `app/`, not `src/app/`. Detected rather than
// hardcoded, because a hardcoded path for one app is a path that is wrong for the
// next one added.

import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();

/** Where each app keeps its Next.js app directory. */
const APPS = [
  { name: 'web', dir: 'src/app' },
  { name: 'admin', dir: 'src/app' },
  { name: 'analytics', dir: 'app' },
  // `billing` also uses a root `app/`, not `src/app/`. The first run of this
  // generator skipped it with "no src/app - check its Next.js convention", which is
  // the check working - and then the mistake was to leave it listed as `src/app`
  // rather than to detect the convention.
  //
  // DETECTED INSTEAD, from here on: a new app gets the right answer without
  // anyone editing this file, which is the only version of this list that stays
  // correct as apps are added.
  { name: 'billing', dir: 'detect' },
  { name: 'currency', dir: 'src/app' },
  { name: 'monitor', dir: 'src/app' },
  { name: 'video-editor', dir: 'src/app' },
  { name: 'superadmin', dir: 'src/app' },
];

const ENDPOINTS = ['start', 'heartbeat', 'end'];

/**
 * The three-line re-export.
 *
 * `dynamic` matters: these are per-user and must never be cached or statically
 * rendered. Without it Next may attempt to prerender the route at build time, and a
 * prerendered "you are not signed in" is a route that can never work.
 */
function routeSource(endpoint) {
  return `// GENERATED by tools/generate-presence-routes.mjs - do not edit by hand.
//
// One of eight identical files. The implementation is shared in
// \`@wideo11/ui/presence-handler\`; this exists only to give the browser a
// same-origin path, because auth-service does not send CORS headers and the
// session credential is an httpOnly cookie the page cannot attach by hand.
//
// Run the generator after changing the shared handler, and it rewrites all eight.

import { forwardPresence } from '@wideo11/ui/presence-handler';

export const dynamic = 'force-dynamic';

// POST takes the request because the relay reads the device headers off it.
//
// The first version took no argument and the relay read the device from a cookie -
// which nothing set. A zero-argument handler cannot be given headers at all, so
// there was no way to fix it downstream; the signature had to change. That is
// recorded here because the failure was silent: the route compiled, returned 200,
// and recorded an empty device on every single request.
export async function POST(request: Request) {
  return forwardPresence(request, '${endpoint}');
}
`;
}

/**
 * Find an app's Next.js app directory.
 *
 * Four apps use `app/` at the repo-app root and four use `src/app/`. Hardcoding
 * that per app is a list that is wrong the moment an app is added, and the first
 * run of this generator got it wrong for `billing` - skipping a real app with a
 * message that read like the app was misconfigured.
 *
 * Detection is unambiguous: `src/app` wins if it exists, otherwise `app`.
 */
function resolveAppDir(appDir) {
  if (existsSync(join(appDir, 'src', 'app'))) return 'src/app';
  if (existsSync(join(appDir, 'app'))) return 'app';
  return 'src/app';
}

let written = 0;
let skipped = 0;

for (const app of APPS) {
  const appDir = join(ROOT, 'apps', app.name);
  if (!existsSync(appDir)) {
    console.log(`  SKIP  ${app.name} (no such app)`);
    skipped++;
    continue;
  }

  const base = join(appDir, app.dir === 'detect' ? resolveAppDir(appDir) : app.dir, 'api', 'auth', 'presence');
  if (!existsSync(join(appDir, resolveAppDir(appDir)))) {
    console.log(`  SKIP  ${app.name} (no Next.js app directory - expected src/app or app)`);
    skipped++;
    continue;
  }

  for (const endpoint of ENDPOINTS) {
    const dir = join(base, endpoint);
    mkdirSync(dir, { recursive: true });
    const file = join(dir, 'route.ts');

    const next = routeSource(endpoint);
    const current = existsSync(file) ? (await import('node:fs')).readFileSync(file, 'utf8') : null;

    // Only rewrite when it differs, so mtimes stay meaningful and a clean tree is
    // not dirtied by a no-op run.
    if (current === next) {
      console.log(`  same  ${app.name}/${endpoint}`);
      continue;
    }
    writeFileSync(file, next);
    console.log(`  write ${app.name}/${endpoint}`);
    written++;
  }
}

console.log(`\n${written} written, ${skipped} app(s) skipped`);
console.log('verify with: node tools/check-presence-routes.mjs');
