package model

import (
	"time"
)

type Subtitle struct {
	ID          uint           `gorm:"primarykey" json:"id"`
	VideoID     uint           `gorm:"not null;index" json:"video_id"`
	Language    string         `gorm:"size:10;not null" json:"language"`
	Label       string         `gorm:"size:100" json:"label"`
	MinioPath   string         `gorm:"type:text;not null" json:"minio_path"`
	FileType    string         `gorm:"size:10;not null" json:"file_type"`
	IsDefault   bool           `gorm:"default:false" json:"is_default"`
	IsForced    bool           `gorm:"default:false" json:"is_forced"`
	Source      string         `gorm:"size:20;default:'upload'" json:"source"`
	AutoGenerated bool         `gorm:"default:false" json:"auto_generated"`
	CreatedAt   time.Time      `gorm:"autoCreateTime" json:"created_at"`
	UpdatedAt   time.Time      `gorm:"autoUpdateTime" json:"updated_at"`
}

func (Subtitle) TableName() string {
	return "subtitles"
}

type SubtitleStyle struct {
	ID          uint           `gorm:"primarykey" json:"id"`
	SubtitleID  uint           `gorm:"not null;index" json:"subtitle_id"`
	FontFamily  string         `gorm:"size:255" json:"font_family"`
	FontSize    string         `gorm:"size:20;default:'100%'" json:"font_size"`
	FontColor   string         `gorm:"size:20;default:'white'" json:"font_color"`
	Outline     string         `gorm:"size:20;default:'black'" json:"outline"`
	OutlineSize string         `gorm:"size:20;default:'1px'" json:"outline_size"`
	Shadow      string         `gorm:"size:20;default:'transparent'" json:"shadow"`
	BackgroundColor string    `gorm:"size:20;default:'rgba(0,0,0,0.5)'" json:"background_color"`
	Alignment   int            `gorm:"default:2" json:"alignment"`
	Position    string         `gorm:"size:50;default:'bottom'" json:"position"`
}

func (SubtitleStyle) TableName() string {
	return "subtitle_styles"
}
